export function downloadTextFile(content: string, filename: string, mimeType: string = 'text/plain') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function exportTargetsCsv(targets: TargetCompany[]): void {
  const headers = [
    'ID',
    'Name',
    'Code Name',
    'Sector',
    'Sub-Sector',
    'Region',
    'ARR ($M)',
    'Growth YoY (%)',
    'EBITDA Margin (%)',
    'Rule of 40',
    'NDR (%)',
    'EV ($M)',
    'EV/ARR',
    'Strategic Score',
    'Potential Synergy ($M)',
    'Deal Readiness',
  ];

  const rows = targets.map((t) => [
    `"${t.id}"`,
    `"${t.name}"`,
    `"${t.codeName}"`,
    `"${t.sector}"`,
    `"${t.subSector}"`,
    `"${t.headquarters.region}"`,
    t.financials.arr,
    t.financials.revenueGrowthYoY,
    t.financials.ebitdaMargin,
    t.financials.ruleOf40,
    t.financials.netDollarRetention,
    t.valuation.targetEnterpriseValue,
    t.valuation.evArrMultiple,
    t.strategicFit.overallScore,
    t.strategicFit.potentialSynergiesRunRateM,
    `"${t.dealReadiness}"`,
  ]);

  const csvContent = [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
  downloadTextFile(csvContent, `M&A_Target_Discovery_Export_${new Date().toISOString().slice(0, 10)}.csv`, 'text/csv');
}
